/* ═══════════════════════════════════════════════════════════════════════
   0. 조사 — 기존 m/index.html 구현과 동일 (유니코드 0xAC00 공식)
   ═══════════════════════════════════════════════════════════════════════ */

/** 마지막 글자에 받침이 있으면 true. 한글이 아니면 false. */
const jong = s => {
  const t = String(s);
  if (!t.length) return false;
  const c = t.charCodeAt(t.length - 1);
  return c >= 0xAC00 && c <= 0xD7A3 ? ((c - 0xAC00) % 28) > 0 : false;
};

/** J('초코','은','는') → '초코는' · J('콩','은','는') → '콩은'  (기존 앱과 동일 시그니처) */
export function J(s, a, b) { return String(s) + (jong(s) ? a : b); }

/** 조사 짝 — 키(받침 있을 때) : 값(받침 없을 때) */
export const JOSA = {
  '은': '는', '이': '가', '을': '를', '과': '와', '아': '야',
  '으로': '로', '이랑': '랑', '이나': '나', '이에요': '예요', '이라고': '라고',
};

/** 카피에서 쓸 수 있는 플레이스홀더 키 (검증기가 이 목록으로 오타를 잡는다) */
export const PLACEHOLDERS = ['name', 'cmd', 'signal', 'unit', 'n', 'lv', 'sign', 'gestureHint', 'sec',
  'breed', 'total', 'succ', 'need'];

/**
 * 카피 렌더러. {name} · {name:은} · {cmd:을} 을 실제 값으로 바꾼다.
 * 앞에 ~ 를 붙이면 «조사만» 나온다 — «{cmd}»{~cmd:을} 처럼 겹낫표 밖에 조사를 둘 때 쓴다.
 * 값이 없는 플레이스홀더는 «일부러» 그대로 남긴다 — 조용히 사라지면 버그를 못 본다.
 */
export function fill(tpl, vars = {}) {
  return String(tpl).replace(/\{(~?)(\w+)(?::([^}]+))?\}/g, (m, only, key, josa) => {
    const v = vars[key];
    if (v == null) return m;
    const s = String(v);
    if (!josa) return only ? '' : s;
    const b = JOSA[josa];
    if (b === undefined) return (only ? '' : s) + josa;   // 미등록 조사 — 검증기가 잡는다
    const full = J(s, josa, b);
    return only ? full.slice(s.length) : full;
  });
}

