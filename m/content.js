/** '정답>오답' 피드백을 찾는다. 없으면 null (호출측이 기본 문구로 폴백). */
export function confusionFor(correctId, wrongId) {
  return CONFUSION[`${correctId}>${wrongId}`] || null;
}

/** 해당 정답 신호에 준비된 오답 목록 — 퀴즈 보기를 «혼동되는 것»으로 고를 때 쓴다. */
export function confusableWith(correctId) {
  return Object.keys(CONFUSION)
    .filter(k => k.startsWith(`${correctId}>`))
    .map(k => k.split('>')[1]);
}

/** 해금 조건을 사람 말로. ctx = { lvOf(cmdId), avgLv } */
export function unlockText(cmdId, ctx = {}) {
  const c = COMMANDS[cmdId];
  if (!c || !c.unlock) return null;
  const [req, lv] = c.unlock;
  if (req === 'avg') return fill(TRAIN_COPY.yard.lockedAvg, { lv });
  return fill(TRAIN_COPY.yard.locked, { cmd: COMMANDS[req] ? COMMANDS[req].name : req, lv });
}

